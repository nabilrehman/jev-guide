// Builds "Jev Guide.app" (in /Applications, or ~/Applications if that isn't writable) so
// jev-guide launches from Spotlight/Launchpad/Dock with no terminal. The app is a thin
// launcher: it runs this checkout's bin/jev-guide.js --agent --app with the current node binary,
// so code changes here take effect without reinstalling.
//   npm run install-app
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const NAME = "Jev Guide";
const appsDir = (() => { try { fs.accessSync("/Applications", fs.constants.W_OK); return "/Applications"; } catch { return path.join(os.homedir(), "Applications"); } })();
const APP = path.join(appsDir, `${NAME}.app`);
const LOG = path.join(os.homedir(), ".jev-guide", "app.log");
// Prefer the PATH symlink (e.g. /usr/local/bin/node) so a `brew upgrade node` doesn't break the app.
const NODE = (() => { try { return execFileSync("which", ["node"], { encoding: "utf8" }).trim() || process.execPath; } catch { return process.execPath; } })();
const q = (s) => `'${s.replace(/'/g, `'\\''`)}'`;

fs.rmSync(APP, { recursive: true, force: true });
fs.mkdirSync(path.join(APP, "Contents", "MacOS"), { recursive: true });
fs.mkdirSync(path.join(APP, "Contents", "Resources"), { recursive: true });

fs.writeFileSync(path.join(APP, "Contents", "Info.plist"), `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>${NAME}</string>
  <key>CFBundleDisplayName</key><string>${NAME}</string>
  <key>CFBundleIdentifier</key><string>local.jev-guide.app</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>CFBundleShortVersionString</key><string>0.1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>jev-guide</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>LSUIElement</key><true/>
  <key>NSMicrophoneUsageDescription</key><string>Jev Guide listens while you hold the talk key so you can say what to do.</string>
  <key>NSSpeechRecognitionUsageDescription</key><string>Jev Guide turns what you say into instructions.</string>
  <key>NSAppleEventsUsageDescription</key><string>Jev Guide controls apps to carry out your instructions.</string>
</dict></plist>
`);

// The bundle's executable must be a real binary, not a script: macOS credits permissions
// (Accessibility, Microphone) to the process that launched the work. With a script as the
// executable, macOS attributed them to "node" instead of Jev Guide. This tiny C launcher
// stays alive as the parent, so node and mac/axhelper run on Jev Guide's permissions.
const launcher = path.join(APP, "Contents", "Resources", "run.sh");
const csrc = path.join(os.tmpdir(), `jev-launcher-${process.pid}.c`);
fs.writeFileSync(csrc, `#include <spawn.h>
#include <sys/wait.h>
#include <mach-o/dyld.h>
#include <libgen.h>
#include <limits.h>
#include <stdio.h>
extern char **environ;
int main(void) {
  char exe[PATH_MAX], script[PATH_MAX]; uint32_t n = sizeof exe;
  if (_NSGetExecutablePath(exe, &n) != 0) return 1;
  snprintf(script, sizeof script, "%s/../Resources/run.sh", dirname(exe));
  char *argv[] = { "/bin/bash", script, NULL };
  pid_t pid; int st = 0;
  if (posix_spawn(&pid, "/bin/bash", NULL, NULL, argv, environ) != 0) return 1;
  waitpid(pid, &st, 0);
  return WIFEXITED(st) ? WEXITSTATUS(st) : 1;
}
`);
execFileSync("clang", ["-O2", "-o", path.join(APP, "Contents", "MacOS", "jev-guide"), csrc]);
fs.rmSync(csrc, { force: true });
fs.writeFileSync(launcher, `#!/bin/bash
# Generated by scripts/install-app.mjs — re-run "npm run install-app" if you move the project.
export PATH="${path.dirname(NODE)}:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:$PATH"
mkdir -p "$HOME/.jev-guide"
cd ${q(ROOT)} || { osascript -e 'display alert "Jev Guide" message "Project folder not found: ${ROOT.replace(/["'\\]/g, "")}"'; exit 1; }
echo "=== $(date) ===" >> ${q(LOG)}
if ! ${q(NODE)} bin/jev-guide.js --agent --app >> ${q(LOG)} 2>&1; then
  msg=$(tail -n 4 ${q(LOG)} | tr '"\\\\' "'/")
  osascript -e "display alert \\"Jev Guide stopped\\" message \\"$msg\\n\\nFull log: ~/.jev-guide/app.log\\""
fi
`);
fs.chmodSync(launcher, 0o755);

// Icon: render an SVG in Chrome, then sips + iconutil into AppIcon.icns.
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "jev-icon-"));
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#4c8dff"/><stop offset="1" stop-color="#1747b8"/></linearGradient></defs>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#g)"/>
  <rect x="422" y="230" width="180" height="340" rx="90" fill="#fff"/>
  <path d="M312 480a200 200 0 0 0 400 0M512 680v110M412 790h200" fill="none" stroke="#fff" stroke-width="48" stroke-linecap="round"/>
  <path d="M700 250l150 88-64 16-36 58z" fill="#ffcc00" stroke="#1747b8" stroke-width="14" stroke-linejoin="round"/>
</svg>`;
const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage({ viewport: { width: 1024, height: 1024 } });
await page.setContent(`<html><body style="margin:0;background:transparent">${svg}</body></html>`);
const png = path.join(tmp, "icon.png");
await page.screenshot({ path: png, omitBackground: true });
await browser.close();
const iconset = path.join(tmp, "AppIcon.iconset");
fs.mkdirSync(iconset);
for (const s of [16, 32, 128, 256, 512]) {
  execFileSync("sips", ["-z", `${s}`, `${s}`, png, "--out", path.join(iconset, `icon_${s}x${s}.png`)], { stdio: "ignore" });
  execFileSync("sips", ["-z", `${s * 2}`, `${s * 2}`, png, "--out", path.join(iconset, `icon_${s}x${s}@2x.png`)], { stdio: "ignore" });
}
execFileSync("iconutil", ["-c", "icns", iconset, "-o", path.join(APP, "Contents", "Resources", "AppIcon.icns")]);
fs.rmSync(tmp, { recursive: true, force: true });

// Ad-hoc signature gives macOS a stable identity for the mic permission.
try { execFileSync("codesign", ["--force", "--deep", "--sign", "-", APP], { stdio: "ignore" }); } catch {}
try { execFileSync("/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister", ["-f", APP]); } catch {}
try { execFileSync("touch", [APP]); } catch {}

console.log(`✓ Installed ${APP}
  Open it from Spotlight (⌘Space → "Jev Guide"). It lives in the menu bar (🎤); hold right Option anywhere to talk.
  First launch: allow "Jev Guide" under System Settings → Privacy & Security → Accessibility and Microphone.
  Quit from the 🎤 menu bar item. Logs: ${LOG}`);
